def add_num(num1,num2):
    sum=num1+num2
    print(sum)
def sub_num(num1,num2):
    sub=num1-num2
    print(sub)
def mult_num(num1,num2):
    mult=num1*num2
    print(mult)
def div_num(num1,num2):
    div=num1//num2
    print(div)
def module_num(num1,num2):
    mod=num1%num2
    print(mod)
